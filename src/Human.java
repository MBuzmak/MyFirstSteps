public class Human {
    private String secret;
    public String news;
    protected String experience;
    String gossip;

    private String getSecret() {
        return this.secret;
    }

    public String getNews() {
        return this.news;
    }

    protected String getExperience() {
        return this.experience;
    }

    String getGossip() {
        return this.gossip;
    }
}
